function plotOptimizedDesignMech( ...
    hx,hy,hz,xPhys,yPhys,pxPhys,pyPhys,pzPhys,U)
% plotOptimizedDesignMech
% -------------------------------------------------------------------------
% Mechanical-only visualization for CFRCTop3D.
%
% Generated figures:
%   1. Displacement magnitude
%   2. Fiber orientation and fiber volume fraction
%
% The temperature field is intentionally omitted.
% -------------------------------------------------------------------------

[nelz,nely,nelx] = size(xPhys);
nNode = (nelx+1)*(nely+1)*(nelz+1);

[Z,Y,X] = ndgrid(0:nelz,0:nely,0:nelx);
coords = [X(:)*hx,Y(:)*hy,Z(:)*hz];

nodenrs = int32(reshape( ...
    1:nNode, ...
    1+nelz,1+nely,1+nelx));

edofVec = reshape( ...
    nodenrs(1:end-1,1:end-1,1:end-1), ...
    [],1);

nids = edofVec + int32([ ...
    0, ...
    (nely+1)*(nelz+1), ...
    (nely+2)*(nelz+1), ...
    nelz+1, ...
    1 + [ ...
        0, ...
        (nely+1)*(nelz+1), ...
        (nely+2)*(nelz+1), ...
        nelz+1]]);

facePattern = [ ...
    1 4 8 5; ...
    4 8 7 3; ...
    3 7 6 2; ...
    2 6 5 1; ...
    1 4 3 2; ...
    8 5 6 7];

xthreshold = 0.5;
validElems = xPhys >= xthreshold;

if ~any(validElems(:))
    warning('No elements satisfy xPhys >= %.3f.',xthreshold);
    return;
end

validNids  = nids(validElems(:),:);
elementFace = reshape( ...
    validNids(:,facePattern')', ...
    4,[])';

%% Displacement magnitude
for k = 1:size(U,2)

    Ux = U(1:3:end,k);
    Uy = U(2:3:end,k);
    Uz = U(3:3:end,k);

    Ushow = sqrt(Ux.^2+Uy.^2+Uz.^2);

    figure( ...
        'Color','w', ...
        'Name','Displacement Field');

    patch( ...
        'Faces',elementFace, ...
        'Vertices',coords, ...
        'FaceVertexCData',Ushow, ...
        'FaceColor','interp', ...
        'EdgeAlpha',0.1, ...
        'EdgeColor','k');

    cLimits = [min(Ushow),max(Ushow)];

    if cLimits(2) <= cLimits(1)
        cLimits(2) = cLimits(1)+eps(max(1,abs(cLimits(1))));
    end

    setup_3d_style( ...
        'Displacement Magnitude', ...
        cLimits, ...
        jet);

    formatColorbarAtMostTwoDecimals();
end

%% Fiber orientation and fiber volume fraction
figure( ...
    'Color','w', ...
    'Name','Fiber Orientation and Fraction');

set(gcf,'Renderer','opengl');
hold on;

patch( ...
    'Faces',elementFace, ...
    'Vertices',coords, ...
    'FaceColor',[0.85,0.85,0.90], ...
    'FaceAlpha',0.20, ...
    'EdgeAlpha',0.05, ...
    'EdgeColor','k');

[CZ,CY,CX] = ndgrid( ...
    (0.5:nelz-0.5)*hz, ...
    (0.5:nely-0.5)*hy, ...
    (0.5:nelx-0.5)*hx);

scale = min([hx,hy,hz])*0.8;

px = pxPhys(validElems)*scale;
py = pyPhys(validElems)*scale;
pz = pzPhys(validElems)*scale;

qHandle = quiver3( ...
    CX(validElems)-px/2, ...
    CY(validElems)-py/2, ...
    CZ(validElems)-pz/2, ...
    px,py,pz, ...
    'AutoScale','off', ...
    'LineWidth',1.2, ...
    'ShowArrowHead','off');

cmapFiber = jet(256);

yMin = min(yPhys(validElems),[],'all');
yMax = max(yPhys(validElems),[],'all');

if yMax <= yMin
    yMax = yMin+eps(max(1,abs(yMin)));
end

normalizedY = ...
    (yPhys(validElems)-yMin)/(yMax-yMin);

colorIndex = ...
    floor(normalizedY*255)+1;

colorIndex = max(1,min(256,colorIndex));

fiberColors = uint8([ ...
    repelem(cmapFiber(colorIndex,:),2,1), ...
    ones(numel(colorIndex)*2,1)].'*255);

try
    set( ...
        qHandle.Tail, ...
        'ColorBinding','interpolated', ...
        'ColorData',fiberColors);
catch
    warning(['Per-segment quiver coloring is not supported by this ', ...
             'MATLAB graphics version. A uniform quiver color is used.']);
end

setup_3d_style( ...
    'Fiber Volume Fraction', ...
    [yMin,yMax], ...
    jet);

formatColorbarAtMostTwoDecimals();

hold off;

end


function formatColorbarAtMostTwoDecimals()
% Format colorbar labels with no more than two decimal places.

drawnow;

cb = findobj(gcf,'Type','ColorBar');

if isempty(cb)
    return;
end

cb = cb(1);

tickLabels = compose('%.2f',cb.Ticks);
tickLabels = regexprep(tickLabels,'(\.\d*?)0+$','$1');
tickLabels = regexprep(tickLabels,'\.$','');

cb.TickLabels = tickLabels;
end
